import {ledger as prepaidLedger} from '../../contracts/contract/prepaid.js';
import {loadModelRouter,ModelRouter} from './models.js';
import { CompactInferenceAdapter } from './compact-inference.js';
import { OpenCodeAdapter } from './opencode.js';
import { WebSocket } from 'ws';
import { mkdirSync,chmodSync } from 'node:fs';
import { dirname } from 'node:path';
import { Gateway, MockAdapter, ProviderAdapter } from './gateway.js';
import { chainReceipts } from './receipt-source.js';
import { server } from './server.js';
import { getConfig } from './config.js';
Object.assign(globalThis,{WebSocket});
const address=process.env.VAULT_ADDRESS;
if(!address)throw new Error('VAULT_ADDRESS is required; deploy via the headless client first');
const config=getConfig();
const mode=process.env.AI_ADAPTER ?? 'mock';
if(!['mock','provider','opencode','opencode-compact'].includes(mode))throw new Error('AI_ADAPTER must be mock, provider, opencode, or opencode-compact');
const base=mode.startsWith('opencode')?new OpenCodeAdapter({model:process.env.OPENCODE_MODEL??'opencode/beam-free',profile:process.env.OPENCODE_PROFILE,skillPath:process.env.OPENCODE_SKILL??'.opencode/skills/midnight-compact/SKILL.md'}):mode==='mock'?new MockAdapter():new ProviderAdapter(process.env.LLM_URL ?? '',process.env.LLM_API_KEY ?? '',process.env.LLM_MODEL ?? '');
const legacy=mode==='opencode-compact'?new CompactInferenceAdapter(base):base;
const adapter=process.env.MODEL_CATALOG?loadModelRouter(process.env.MODEL_CATALOG):new ModelRouter([{info:{id:'default',label:'Configured AI model',adapter:mode,credits:1},adapter:legacy}],'default');
const path=process.env.GATEWAY_DB ?? '.private-states/gateway.db';
mkdirSync(dirname(path),{recursive:true,mode:0o700});
process.umask(0o077);
const funding=process.env.FUNDING_MODE??'simulated-yield';if(!['prepaid','simulated-yield'].includes(funding))throw new Error('Invalid funding mode');
const gateway=new Gateway(chainReceipts(address,config.indexer,config.indexerWS,config.node,funding==='prepaid'?prepaidLedger:undefined),adapter,path);
chmodSync(path,0o600);
const app=server(gateway,config.networkId,address,mode,funding);app.requestTimeout=390000;app.headersTimeout=10000;
app.listen(Number(process.env.PORT ?? 8787),'127.0.0.1',()=>console.info(`ShadowCompute gateway listening on loopback; AI adapter=${mode}; funding=${funding}`));
function shutdown(){app.close(()=>{gateway.close();process.exit(0);});}
process.on('SIGTERM',shutdown);process.on('SIGINT',shutdown);
