import { readFileSync,writeFileSync,mkdirSync,existsSync } from 'node:fs';
import { resolve,join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { Sim,assertNotInPublicState } from '../packages/contracts/sim.ts';
const file=process.argv[2];if(!file)throw new Error('Usage: npm run check:generated -- ANSWER_FILE');
const text=readFileSync(file,'utf8'),match=text.match(/```(?:compact)?\s*\n([\s\S]*?)```/i);
const source=(match?match[1]:text).trim();
assert(source.length<20000,'Generated source too large');
assert(source.includes('pragma language_version 0.28;'),'Expected current Compact 0.28');
assert(!/\binclude\b/.test(source),'No external source includes');
const imports=[...source.matchAll(/\bimport\s+([^;]+);/g)];
assert(imports.length===1&&imports[0][1].trim()==='CompactStandardLibrary','Only the standard library may be imported');
const dir=resolve(process.argv[3]??'artifacts/generated-budget');
assert(dir.startsWith(resolve('artifacts')+'/'),'Generated checks must stay under project artifacts');
assert(!existsSync(join(dir,'deployment.json')),'Do not overwrite evidence for an already-deployed generated contract');
mkdirSync(dir,{recursive:true});
const compactFile=join(dir,'private-budget.compact');writeFileSync(compactFile,source+'\n');
const run=spawnSync('compact',['compile','+0.36.1',compactFile,join(dir,'managed')],{encoding:'utf8',timeout:180000});
writeFileSync(join(dir,'compile.log'),(run.stdout??'')+(run.stderr??''));
assert.equal(run.status,0,`Generated contract failed actual compilation: ${run.stderr}`);
const {Contract,ledger}=await import(pathToFileURL(join(dir,'managed/contract/index.js')).href);
const secretKey=new Uint8Array(randomBytes(32));
const contract=new Contract({secretKey:({privateState})=>[privateState,privateState.secretKey]});
assert.deepEqual(Object.keys(contract.impureCircuits),['spend'],'No extra public mutation entrypoints');
await assert.rejects(()=>Sim.deploy({contract,ledger,privateState:{secretKey},args:[0n]}));
const sim=await Sim.deploy({contract,ledger,privateState:{secretKey},args:[10n]});
assert.deepEqual(Object.keys(sim.ledger()).sort(),['cap','owner','spent']);
assert.equal(sim.ledger().spent,0n);assert.equal(sim.ledger().cap,10n);
await sim.call('spend',3n);assert.equal(sim.ledger().spent,3n);
sim.privateState={secretKey:new Uint8Array(randomBytes(32))};await assert.rejects(()=>sim.call('spend',1n));assert.equal(sim.ledger().spent,3n);
sim.privateState={secretKey};await assert.rejects(()=>sim.call('spend',0n));await assert.rejects(()=>sim.call('spend',8n));
await assert.rejects(()=>sim.call('spend',(2n**64n)-1n));assert.equal(sim.ledger().spent,3n);
await sim.call('spend',7n);assert.equal(sim.ledger().spent,10n);await assert.rejects(()=>sim.call('spend',1n));
assertNotInPublicState(sim.ledger(),{secretKey});
writeFileSync(join(dir,'verification.json'),JSON.stringify({compiler:'0.36.1',language:'0.28',compiledWithRealZkKeys:true,tests:['initial-budget','authorized-spend','unauthorized-rejection','zero-rejection','over-budget-rejection','exact-cap','exhaustion','public-secret-leak-check','exported-entrypoints','constructor-zero-rejection','exact-ledger-fields','overflow-rejection'],passed:12,generatedSource:compactFile,at:new Date().toISOString()},null,2));
console.info('AI-generated Compact: compiled with real proving keys; 12 behavioral/privacy checks passed.');
